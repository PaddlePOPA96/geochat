import fs from 'fs'
import { execSync } from 'child_process'
import path from 'path'

console.log('🚀 Building ChatGuessr Standalone Executable...')

// 1. Generate embedded HTML templates
console.log('1. Embedding dashboard & overlay templates...')
const dHtml = fs.readFileSync('public/dashboard/index.html', 'utf8')
const oHtml = fs.readFileSync('public/overlay/index.html', 'utf8')
const content = `// Auto-generated by build script
export const embeddedDashboardHtml = ${JSON.stringify(dHtml)};
export const embeddedOverlayHtml = ${JSON.stringify(oHtml)};
`
fs.writeFileSync('src/server/embeddedTemplates.ts', content, 'utf8')

// 2. Bundle with esbuild
console.log('2. Bundling server with esbuild...')
fs.mkdirSync('dist', { recursive: true })
fs.mkdirSync('bin', { recursive: true })
execSync(
  'npx -y esbuild src/server/index.ts --bundle --platform=node --target=node20 --format=cjs --outfile=dist/server-bundle.cjs',
  { stdio: 'inherit' }
)

// 3. Compile standalone binaries with pkg
// IMPORTANT: target must match the installed Node.js major version (node20)
// Using node22 target on node20 causes force-close / crash at startup
console.log('3. Compiling Windows & Mac binaries with pkg...')
execSync(
  'npx -y @yao-pkg/pkg@5.15.0 dist/server-bundle.cjs --targets node20-win-x64,node20-macos-x64 --out-path bin',
  { stdio: 'inherit' }
)

// Rename to clean user-friendly filenames
const winCandidates = ['bin/server-bundle-win.exe', 'bin/server-bundle-win-x64.exe']
for (const f of winCandidates) {
  if (fs.existsSync(f)) {
    fs.copyFileSync(f, 'bin/MabarBang.exe')
    fs.copyFileSync(f, 'bin/ChatGuessr.exe')
    try { fs.unlinkSync(f) } catch (_) {}
  }
}

const macCandidates = ['bin/server-bundle-macos', 'bin/server-bundle-macos-x64']
for (const f of macCandidates) {
  if (fs.existsSync(f)) {
    fs.copyFileSync(f, 'bin/MabarBang-macos')
    fs.copyFileSync(f, 'bin/ChatGuessr-macos')
    try { fs.unlinkSync(f) } catch (_) {}
  }
}

console.log('✅ Build Complete!')
console.log('📁 Windows Exe: bin/MabarBang.exe (dan bin/ChatGuessr.exe)')
console.log('📁 Mac Binary : bin/MabarBang-macos')
