import fs from 'fs'
import { execSync } from 'child_process'
import path from 'path'

console.log('🚀 Building ChatGuessr Standalone Executable...')

// 1. Generate embedded HTML templates
console.log('1. Embedding dashboard & overlay templates...')
const dHtml = fs.readFileSync('public/dashboard/index.html', 'utf8')
const oHtml = ''
const uScript = fs.existsSync('userscript/chatguessr-connector.user.js')
  ? fs.readFileSync('userscript/chatguessr-connector.user.js', 'utf8')
  : ''
const content = `// Auto-generated by build script
export const embeddedDashboardHtml = ${JSON.stringify(dHtml)};
export const embeddedOverlayHtml = "";
export const embeddedUserscript = ${JSON.stringify(uScript)};
`
fs.writeFileSync('src/server/embeddedTemplates.ts', content, 'utf8')

// 2. Bundle with esbuild
console.log('2. Bundling server with esbuild...')
fs.mkdirSync('dist', { recursive: true })
fs.mkdirSync('bin', { recursive: true })
execSync(
  'npx -y esbuild src/server/index.ts --bundle --platform=node --target=node20 --format=cjs --outfile=dist/server-bundle.cjs',
  { stdio: 'inherit' }
)

// 3. Compile standalone binary with pkg (Windows only)
console.log('3. Compiling Windows binary with pkg...')
execSync(
  'npx -y @yao-pkg/pkg@5.15.0 dist/server-bundle.cjs --targets node20-win-x64 --output bin/MabarBang.exe',
  { stdio: 'inherit' }
)

// Fallback rename if pkg placed it in a default candidate name
const winCandidates = [
  'bin/server-bundle.exe',
  'bin/server-bundle-win.exe',
  'bin/server-bundle-win-x64.exe'
]
for (const f of winCandidates) {
  if (fs.existsSync(f)) {
    if (!fs.existsSync('bin/MabarBang.exe')) {
      fs.copyFileSync(f, 'bin/MabarBang.exe')
    }
    try { fs.unlinkSync(f) } catch (_) {}
  }
}

if (!fs.existsSync('bin/MabarBang.exe')) {
  const anyExe = fs.readdirSync('bin').find((f) => f.endsWith('.exe'))
  if (anyExe) {
    fs.copyFileSync(path.join('bin', anyExe), 'bin/MabarBang.exe')
  }
}

console.log('✅ Build Complete! bin/MabarBang.exe siap.')
