import fs from 'fs'
import { execSync } from 'child_process'
import path from 'path'

console.log('🚀 Building MabarBang Standalone Executable...')

// 1. Generate embedded HTML templates
console.log('1. Embedding dashboard & overlay templates...')
const dHtml = fs.readFileSync('public/dashboard/index.html', 'utf8')
const oHtml = ''
const uScript = fs.existsSync('userscript/chatguessr-connector.user.js')
  ? fs.readFileSync('userscript/chatguessr-connector.user.js', 'utf8')
  : ''
// Obfuscate Supabase public config for standalone mode
let envConfig = {}
if (fs.existsSync('.env')) {
  const lines = fs.readFileSync('.env', 'utf8').split('\n')
  for (const line of lines) {
    const t = line.trim()
    if (t && !t.startsWith('#')) {
      const eq = t.indexOf('=')
      if (eq !== -1) {
        envConfig[t.substring(0, eq).trim()] = t.substring(eq + 1).trim()
      }
    }
  }
}

const rawUrl = envConfig.SUPABASE_URL || envConfig.VITE_SUPABASE_URL || process.env.SUPABASE_URL || ''
const rawKey = envConfig.SUPABASE_ANON_KEY || envConfig.VITE_SUPABASE_ANON_KEY || process.env.SUPABASE_ANON_KEY || ''

function obscure(str, salt = 0xa5) {
  if (!str) return ''
  const buf = Buffer.from(str, 'utf8')
  const out = Buffer.alloc(buf.length)
  for (let i = 0; i < buf.length; i++) {
    out[i] = buf[i] ^ salt ^ ((i * 31 + 17) & 0xff)
  }
  return out.toString('base64')
}

// If .env is missing (e.g. on GitHub Actions runner), preserve existing obscured credentials
let existingSecUrl = ''
let existingSecKey = ''
if (fs.existsSync('src/server/embeddedTemplates.ts')) {
  try {
    const prevContent = fs.readFileSync('src/server/embeddedTemplates.ts', 'utf8')
    const urlM = prevContent.match(/embeddedSecUrl\s*=\s*(".*?"|'.*?')/)
    if (urlM) existingSecUrl = JSON.parse(urlM[1])
    const keyM = prevContent.match(/embeddedSecKey\s*=\s*(".*?"|'.*?')/)
    if (keyM) existingSecKey = JSON.parse(keyM[1])
  } catch (_) {}
}

const finalSecUrl = rawUrl ? obscure(rawUrl) : existingSecUrl
const finalSecKey = rawKey ? obscure(rawKey) : existingSecKey

const content = `// Auto-generated by build script
export const embeddedDashboardHtml = ${JSON.stringify(dHtml)};
export const embeddedOverlayHtml = "";
export const embeddedUserscript = ${JSON.stringify(uScript)};
export const embeddedSecUrl = ${JSON.stringify(finalSecUrl)};
export const embeddedSecKey = ${JSON.stringify(finalSecKey)};
`
fs.writeFileSync('src/server/embeddedTemplates.ts', content, 'utf8')

// 2. Bundle with esbuild
console.log('2. Bundling server with esbuild...')
fs.mkdirSync('dist', { recursive: true })
fs.mkdirSync('bin', { recursive: true })
execSync(
  'npx -y esbuild src/server/index.ts --bundle --platform=node --target=node20 --format=cjs --outfile=dist/server-bundle.cjs',
  { stdio: 'inherit' }
)

// 3. Compile standalone binary with pkg (Windows only)
console.log('3. Compiling Windows binary with pkg...')
execSync(
  'npx -y @yao-pkg/pkg@5.15.0 dist/server-bundle.cjs --targets node20-win-x64 --output bin/MabarBang.exe',
  { stdio: 'inherit' }
)

// Fallback rename if pkg placed it in a default candidate name
const winCandidates = [
  'bin/server-bundle.exe',
  'bin/server-bundle-win.exe',
  'bin/server-bundle-win-x64.exe'
]
for (const f of winCandidates) {
  if (fs.existsSync(f)) {
    if (!fs.existsSync('bin/MabarBang.exe')) {
      fs.copyFileSync(f, 'bin/MabarBang.exe')
    }
    try { fs.unlinkSync(f) } catch (_) {}
  }
}

if (!fs.existsSync('bin/MabarBang.exe')) {
  const anyExe = fs.readdirSync('bin').find((f) => f.endsWith('.exe'))
  if (anyExe) {
    fs.copyFileSync(path.join('bin', anyExe), 'bin/MabarBang.exe')
  }
}

console.log('✅ Build Complete! bin/MabarBang.exe siap.')
