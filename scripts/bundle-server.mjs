import fs from 'fs'
import { execSync } from 'child_process'

console.log('⚡ Bundling MabarBang Server...')

// 1. Generate embedded HTML templates & userscript
console.log('1. Embedding dashboard, overlay & userscript...')
const dHtml = fs.readFileSync('public/dashboard/index.html', 'utf8')
const oHtml = ''
const uScript = fs.existsSync('userscript/chatguessr-connector.user.js')
  ? fs.readFileSync('userscript/chatguessr-connector.user.js', 'utf8')
  : ''
// Obfuscate Supabase public config for standalone mode
let envConfig = {}
const envPath = 'path' in fs ? '.env' : '.env'
if (fs.existsSync('.env')) {
  const lines = fs.readFileSync('.env', 'utf8').split('\n')
  for (const line of lines) {
    const t = line.trim()
    if (t && !t.startsWith('#')) {
      const eq = t.indexOf('=')
      if (eq !== -1) {
        envConfig[t.substring(0, eq).trim()] = t.substring(eq + 1).trim()
      }
    }
  }
}

const rawUrl = envConfig.SUPABASE_URL || envConfig.VITE_SUPABASE_URL || process.env.SUPABASE_URL || ''
const rawKey = envConfig.SUPABASE_ANON_KEY || envConfig.VITE_SUPABASE_ANON_KEY || process.env.SUPABASE_ANON_KEY || ''

function obscure(str, salt = 0xa5) {
  if (!str) return ''
  const buf = Buffer.from(str, 'utf8')
  const out = Buffer.alloc(buf.length)
  for (let i = 0; i < buf.length; i++) {
    out[i] = buf[i] ^ salt ^ ((i * 31 + 17) & 0xff)
  }
  return out.toString('base64')
}

const content = `// Auto-generated by build script
export const embeddedDashboardHtml = ${JSON.stringify(dHtml)};
export const embeddedOverlayHtml = "";
export const embeddedUserscript = ${JSON.stringify(uScript)};
export const embeddedSecUrl = ${JSON.stringify(obscure(rawUrl))};
export const embeddedSecKey = ${JSON.stringify(obscure(rawKey))};
`
fs.writeFileSync('src/server/embeddedTemplates.ts', content, 'utf8')

// 2. Bundle with esbuild
console.log('2. Bundling server with esbuild...')
fs.mkdirSync('dist', { recursive: true })
execSync(
  'npx esbuild src/server/index.ts --bundle --platform=node --target=node20 --format=cjs --outfile=dist/server-bundle.cjs',
  { stdio: 'inherit' }
)

// Copy bundle directly to root as server.cjs
fs.copyFileSync('dist/server-bundle.cjs', 'server.cjs')

console.log('✅ Server bundle siap: server.cjs')
